#!/usr/bin/env node
/**
 * PROVE THE OPERATOR ARTIFACT'S ATOMICITY — by EXECUTING it, not by reasoning about it.
 *
 * ★ WHY THIS EXISTS. The deployment runbook makes three claims about what an operator will
 * experience in the Supabase Web SQL Editor: the artifact is pure SQL, it runs in one transaction,
 * and a mid-bundle failure leaves the database exactly as it was. Those are claims about RUN-TIME
 * BEHAVIOUR, and a runbook that asserts them from source inspection is asserting the thing that
 * matters least. Postgres semantics are what actually decide the outcome, so this script puts the
 * generated bytes through a real Postgres and observes.
 *
 * ★ IT NEVER TOUCHES PRODUCTION. An ephemeral container, created and destroyed here. The editor's
 * own client behaviour (how it splits or wraps statements) remains outside any instrument available
 * to me — which is exactly why the artifact carries its OWN `begin; … commit;`: correctness must
 * not depend on the tool. That residual unknown is reported as UNVERIFIABLE rather than assumed
 * away.
 *
 * Three things are established, each with a control:
 *
 *   1 · PURE SQL — no line in any artifact is a psql meta-command.
 *   2 · APPLIES — each artifact runs to completion against a schema-bearing Postgres.
 *   3 · ROLLS BACK — with ONE statement corrupted mid-artifact, the run fails AND every object the
 *       artifact would have created is absent afterwards. The positive control for step 3 is step
 *       2: the same artifact, uncorrupted, does create them.
 *
 * Usage:  node scripts/verifyBundleAtomicity.mjs
 * Exit:   0 proven · 1 a claim failed · 2 could not verify (never a pass)
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SQL_BUNDLES } from './lib/sqlSuiteParts.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONTAINER = 'aw-bundle-atomicity';
const PREAMBLE = 'db/tests/preamble_real_auth.sql';

const die = (code, msg, extra = []) => {
  console.error(`\n✗ ${msg}`);
  for (const e of extra) console.error(`    ${e}`);
  cleanup();
  process.exit(code);
};
let cleanup = () => {};

const ARTIFACTS = SQL_BUNDLES.map(([, artifact]) => artifact);
for (const a of ARTIFACTS) {
  if (!existsSync(join(ROOT, a))) die(2, `CANNOT VERIFY — missing artifact ${a}`);
}

/* ── 1 · PURE SQL ────────────────────────────────────────────────────────────────────────────── */
console.log('1 · PURE SQL — no psql meta-commands in any operator artifact\n');
let metaFail = false;
for (const a of ARTIFACTS) {
  const strays = readFileSync(join(ROOT, a), 'utf8')
    .split('\n')
    .map((l, i) => [i + 1, l])
    .filter(([, l]) => /^\s*\\[a-zA-Z]/.test(l));
  console.log(`  ${strays.length === 0 ? '✓' : '✗'} ${a.padEnd(52)} ${strays.length} meta-command(s)`);
  if (strays.length) {
    metaFail = true;
    for (const [n, l] of strays.slice(0, 3)) console.log(`      line ${n}: ${l.trim()}`);
  }
}
// ★ CONTROL: the SOURCE migrations still carry the directive, so this check is discriminating
// rather than matching nothing. If sources ever lose it too, the stripper is untested.
const sourceMeta = readFileSync(join(ROOT, 'db/migrations/0055_20260812_release_authorization.sql'), 'utf8')
  .split('\n').filter((l) => /^\s*\\[a-zA-Z]/.test(l)).length;
if (sourceMeta === 0) {
  die(2, 'CONTROL FAILED — the source migration carries no meta-command either, so "the artifact '
    + 'has none" proves nothing about the stripper.');
}
console.log(`  · control: the SOURCE migration still has ${sourceMeta} (so the check discriminates)\n`);
if (metaFail) die(1, 'an operator artifact contains a psql meta-command');

/* ── postgres ────────────────────────────────────────────────────────────────────────────────── */
if (spawnSync('docker', ['info'], { stdio: 'ignore' }).status !== 0) {
  die(2, 'CANNOT VERIFY — Docker is not running.',
    ['Atomicity is a run-time property; it must be executed, not described.']);
}
spawnSync('docker', ['rm', '-f', CONTAINER], { stdio: 'ignore' });
if (spawnSync('docker', ['run', '-d', '--name', CONTAINER, '-e', 'POSTGRES_PASSWORD=pw', 'postgres:16'],
  { encoding: 'utf8' }).status !== 0) die(2, 'CANNOT VERIFY — failed to start postgres');
cleanup = () => spawnSync('docker', ['rm', '-f', CONTAINER], { stdio: 'ignore' });
process.on('exit', cleanup);

let ready = false;
for (let i = 0; i < 60; i += 1) {
  if (spawnSync('docker', ['exec', CONTAINER, 'pg_isready', '-U', 'postgres'], { stdio: 'ignore' }).status === 0) {
    ready = true; break;
  }
  execFileSync('sleep', ['1']);
}
if (!ready) die(2, 'CANNOT VERIFY — postgres never became ready');

const psql = (sql, extra = []) => spawnSync(
  'docker', ['exec', '-i', CONTAINER, 'psql', '-U', 'postgres', ...extra, '-f', '-'],
  { input: sql, encoding: 'utf8' });

// The dependency schema, from the maintained harness (never a second hand-written copy).
{
  const r = psql(readFileSync(join(ROOT, PREAMBLE), 'utf8'), ['-v', 'ON_ERROR_STOP=1']);
  if (r.status !== 0) die(2, `CANNOT VERIFY — preamble failed:\n${(r.stderr || '').slice(-800)}`);
}

/** Objects each artifact is expected to create — the observable used for the rollback proof. */
const WITNESS = {
  'db/bundles/release_conditions_bundle.sql':
    "select to_regprocedure('public.release_condition_satisfied(text,timestamptz,text,text)') is not null",
  'db/bundles/estate_inventory_and_discovery_bundle.sql':
    "select to_regprocedure('public.get_estate_discovery(uuid)') is not null",
  'db/bundles/lifecycle_notifications_bundle.sql':
    "select to_regprocedure('public.emit_lifecycle_notification(uuid,uuid,text,text)') is not null",
  'db/bundles/death_verification_bundle.sql':
    "select to_regprocedure('public.authorize_release(uuid,text)') is not null",
};

const witnessTrue = (q) => {
  const r = psql(`${q};`, ['-A', '-t']);
  return (r.stdout ?? '').trim() === 't';
};

/* ── 2 · APPLIES · and 3 · ROLLS BACK ────────────────────────────────────────────────────────── */
console.log('2 · APPLIES · 3 · ROLLS BACK ON MID-ARTIFACT FAILURE\n');
let failed = false;
for (const a of ARTIFACTS) {
  const sql = readFileSync(join(ROOT, a), 'utf8');
  const witness = WITNESS[a];
  if (!witness) die(2, `CANNOT VERIFY — no witness object defined for ${a}`);

  /**
   * ★ THE CORRUPTION GOES AT A PROVABLY TOP-LEVEL BOUNDARY, AFTER REAL WORK HAS BEEN DONE.
   *
   * The first version spliced at an arbitrary line offset and the instrument reported failure for
   * every bundle — correctly, and not for the reason it appeared. An arbitrary line can land INSIDE
   * a `$function$ … $function$` body, where the injected statement becomes part of the function's
   * stored text instead of a statement: the file then applies perfectly, no error occurs, and the
   * "rollback" check is measuring nothing. That is the vacuous direction, and it is why the
   * injection point is now the `-- ==== <path> ====` separator the bundler writes BETWEEN parts —
   * a position guaranteed to be at statement level and outside every dollar-quoted body.
   *
   * A separator past the start is chosen so the transaction has genuinely created objects before it
   * dies; injecting at the top would abort before anything existed and prove rollback vacuously.
   */
  const lines = sql.split('\n');
  const boundaries = lines
    .map((l, i) => [l, i])
    .filter(([l]) => /^-- ==== /.test(l))
    .map(([, i]) => i);
  if (boundaries.length < 2) {
    die(2, `CANNOT VERIFY — ${a} has ${boundaries.length} part separator(s); the injection point `
      + 'must be a top-level boundary, and there is no second one to use.');
  }
  const at = boundaries[Math.max(1, Math.floor(boundaries.length / 2))];
  const corrupted = [...lines.slice(0, at),
    'select this_function_does_not_exist_aw_probe();',
    ...lines.slice(at)].join('\n');

  /**
   * ★ THE VERDICT IS THE DATABASE STATE, NOT PSQL'S EXIT CODE. Whether a client stops at the first
   * error is a client setting (`ON_ERROR_STOP`), and the Supabase editor's choice is not knowable
   * here — which is the whole reason the artifact carries its own transaction. So the question
   * asked is the one that survives any client: after a mid-file error, does the object exist?
   *
   * Run WITHOUT ON_ERROR_STOP deliberately: that is the WEAKER client behaviour (keep going after
   * an error), so proving rollback under it proves it under the stricter one too.
   */
  const rBad = psql(corrupted);
  const erroredBad = /ERROR/.test(`${rBad.stderr ?? ''}${rBad.stdout ?? ''}`);
  const survivedBad = witnessTrue(witness);
  const rollbackOk = erroredBad && !survivedBad;

  const rGood = psql(sql);
  const appliedOk = rGood.status === 0 && witnessTrue(witness);

  console.log(`  ${appliedOk ? '✓' : '✗'} ${a.split('/').pop().padEnd(46)} applies=${appliedOk}  rollback=${rollbackOk}`);
  if (!appliedOk) {
    console.log(`      apply stderr: ${(rGood.stderr || '').trim().split('\n').slice(-2).join(' | ')}`);
    failed = true;
  }
  if (!rollbackOk) {
    console.log('      ✗ a mid-artifact failure did NOT roll back cleanly');
    console.log(`        error_observed=${erroredBad}  witness_present_after_failure=${survivedBad}`);
    if (!erroredBad) {
      console.log('        (no error was even produced — the injection did not land at statement level,');
      console.log('         so this run proves nothing; fix the instrument before trusting a verdict)');
    }
    failed = true;
  }
}

cleanup();
if (failed) {
  console.error('\n✗ ATOMICITY NOT PROVEN — do not hand these artifacts to an operator.');
  process.exit(1);
}
console.log('\n✓ OPERATOR ARTIFACTS ARE PURE SQL, APPLY CLEANLY, AND ROLL BACK COMPLETELY');
console.log('  Each was executed against a real Postgres: once corrupted mid-file (must fail and');
console.log('  leave nothing behind) and once intact (must succeed and create its witness object).');
console.log('  NOT established here: how the Supabase Web SQL Editor itself splits or wraps a paste.');
console.log('  That is why each artifact carries its own begin;/commit; — correctness does not');
console.log('  depend on the editor, so that residual unknown is UNVERIFIABLE rather than assumed.');
