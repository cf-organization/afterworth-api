#!/usr/bin/env node
/**
 * PROVE THE OPERATOR ARTIFACT'S ATOMICITY — by EXECUTING it, not by reasoning about it.
 *
 * ★ WHY THIS EXISTS. The deployment runbook makes three claims about what an operator will
 * experience in the Supabase Web SQL Editor: the artifact is pure SQL, it runs in one transaction,
 * and a mid-bundle failure leaves the database exactly as it was. Those are claims about RUN-TIME
 * BEHAVIOUR, and a runbook that asserts them from source inspection is asserting the thing that
 * matters least. Postgres semantics are what actually decide the outcome, so this script puts the
 * generated bytes through a real Postgres and observes.
 *
 * ★ IT NEVER TOUCHES PRODUCTION. An ephemeral container, created and destroyed here. The editor's
 * own client behaviour (how it splits or wraps statements) remains outside any instrument available
 * to me — which is exactly why the artifact carries its OWN `begin; … commit;`: correctness must
 * not depend on the tool. That residual unknown is reported as UNVERIFIABLE rather than assumed
 * away.
 *
 * Three things are established, each with a control:
 *
 *   1 · PURE SQL — no line in any artifact is a psql meta-command.
 *   2 · APPLIES — each artifact runs to completion against a schema-bearing Postgres.
 *   3 · ROLLS BACK — with ONE statement corrupted mid-artifact, the run fails AND every object the
 *       artifact would have created is absent afterwards. The positive control for step 3 is step
 *       2: the same artifact, uncorrupted, does create them.
 *
 * Usage:  node scripts/verifyBundleAtomicity.mjs
 * Exit:   0 proven · 1 a claim failed · 2 could not verify (never a pass)
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SQL_BUNDLES } from './lib/sqlSuiteParts.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONTAINER = 'aw-bundle-atomicity';
const PREAMBLE = 'db/tests/preamble_real_auth.sql';

const die = (code, msg, extra = []) => {
  console.error(`\n✗ ${msg}`);
  for (const e of extra) console.error(`    ${e}`);
  cleanup();
  process.exit(code);
};
let cleanup = () => {};

const ARTIFACTS = SQL_BUNDLES.map(([, artifact]) => artifact);
for (const a of ARTIFACTS) {
  if (!existsSync(join(ROOT, a))) die(2, `CANNOT VERIFY — missing artifact ${a}`);
}

/* ── 1 · PURE SQL ────────────────────────────────────────────────────────────────────────────── */
console.log('1 · PURE SQL — no psql meta-commands in any operator artifact\n');
let metaFail = false;
for (const a of ARTIFACTS) {
  const strays = readFileSync(join(ROOT, a), 'utf8')
    .split('\n')
    .map((l, i) => [i + 1, l])
    .filter(([, l]) => /^\s*\\[a-zA-Z]/.test(l));
  console.log(`  ${strays.length === 0 ? '✓' : '✗'} ${a.padEnd(52)} ${strays.length} meta-command(s)`);
  if (strays.length) {
    metaFail = true;
    for (const [n, l] of strays.slice(0, 3)) console.log(`      line ${n}: ${l.trim()}`);
  }
}
// ★ CONTROL: the SOURCE migrations still carry the directive, so this check is discriminating
// rather than matching nothing. If sources ever lose it too, the stripper is untested.
const sourceMeta = readFileSync(join(ROOT, 'db/migrations/0055_20260812_release_authorization.sql'), 'utf8')
  .split('\n').filter((l) => /^\s*\\[a-zA-Z]/.test(l)).length;
if (sourceMeta === 0) {
  die(2, 'CONTROL FAILED — the source migration carries no meta-command either, so "the artifact '
    + 'has none" proves nothing about the stripper.');
}
console.log(`  · control: the SOURCE migration still has ${sourceMeta} (so the check discriminates)\n`);
if (metaFail) die(1, 'an operator artifact contains a psql meta-command');

/* ── postgres ────────────────────────────────────────────────────────────────────────────────── */
if (spawnSync('docker', ['info'], { stdio: 'ignore' }).status !== 0) {
  die(2, 'CANNOT VERIFY — Docker is not running.',
    ['Atomicity is a run-time property; it must be executed, not described.']);
}
spawnSync('docker', ['rm', '-f', CONTAINER], { stdio: 'ignore' });
if (spawnSync('docker', ['run', '-d', '--name', CONTAINER, '-e', 'POSTGRES_PASSWORD=pw', 'postgres:16'],
  { encoding: 'utf8' }).status !== 0) die(2, 'CANNOT VERIFY — failed to start postgres');
cleanup = () => spawnSync('docker', ['rm', '-f', CONTAINER], { stdio: 'ignore' });
process.on('exit', cleanup);

let ready = false;
for (let i = 0; i < 60; i += 1) {
  if (spawnSync('docker', ['exec', CONTAINER, 'pg_isready', '-U', 'postgres'], { stdio: 'ignore' }).status === 0) {
    ready = true; break;
  }
  execFileSync('sleep', ['1']);
}
if (!ready) die(2, 'CANNOT VERIFY — postgres never became ready');

const psql = (sql, extra = []) => spawnSync(
  'docker', ['exec', '-i', CONTAINER, 'psql', '-U', 'postgres', ...extra, '-f', '-'],
  { input: sql, encoding: 'utf8' });

// The dependency schema, from the maintained harness (never a second hand-written copy).
{
  const r = psql(readFileSync(join(ROOT, PREAMBLE), 'utf8'), ['-v', 'ON_ERROR_STOP=1']);
  if (r.status !== 0) die(2, `CANNOT VERIFY — preamble failed:\n${(r.stderr || '').slice(-800)}`);
}

/** Objects each artifact is expected to create — the observable used for the rollback proof. */
const classified = [];

const WITNESS = {
  'db/bundles/release_conditions_bundle.sql':
    "select to_regprocedure('public.release_condition_satisfied(text,timestamptz,text,text)') is not null",
  'db/bundles/estate_inventory_and_discovery_bundle.sql':
    "select to_regprocedure('public.get_estate_discovery(uuid)') is not null",
  'db/bundles/lifecycle_notifications_bundle.sql':
    "select to_regprocedure('public.emit_lifecycle_notification(uuid,uuid,text,text)') is not null",
  'db/bundles/death_verification_bundle.sql':
    "select to_regprocedure('public.authorize_release(uuid,text)') is not null",
  // ★ Phase 11-I ships exactly one new name, so the witness IS the whole payload: if the function
  // exists the bundle applied, and if it does not the bundle left nothing behind.
  /**
   * ★ THE WITNESS IS A PRIVILEGE, NOT AN OBJECT. This artifact creates nothing, so "does the object
   * exist" cannot testify. The observable is whether `authenticated` still holds EXECUTE: true
   * before the artifact applies, false after. has_function_privilege answers exactly that.
   */
  'db/bundles/estate_release_state_lockdown_bundle.sql':
    "select not has_function_privilege('authenticated', 'public.estate_release_state(uuid)', 'execute')",
  'db/bundles/executor_workspace_bundle.sql':
    "select to_regprocedure('public.get_executor_workspace(uuid)') is not null",
  /**
   * ★ PHASE 11-K. The witness is the CASE FILE projection rather than the constraint 0056 widens,
   * and deliberately: a CHECK constraint is altered by dropping and re-adding, so a half-applied
   * bundle could leave the table with NO status constraint at all — a state in which the witness
   * "does the constraint admit outcomeUncertain" would answer FALSE for two opposite reasons
   * (never applied, or applied and then rolled back mid-drop). A function that either exists or
   * does not cannot be ambiguous that way, and `admin_get_death_verification_case` is the LAST
   * object this bundle creates, so its presence testifies that everything before it landed too.
   */
  'db/bundles/operator_console_bundle.sql':
    "select to_regprocedure('public.admin_get_death_verification_case(uuid)') is not null",
  /**
   * ★ PHASE 11-L. This artifact CREATES NO NEW NAME — it replaces two existing functions — so
   * `to_regprocedure(...) is not null` cannot testify: both names exist before it runs and after.
   * The only observable state delta is CATALOG CONTENT: whether the copy catalog answers for
   * `death_process.halted`.
   *
   * ★ AND IT WILL REPORT NO_STATE_DELTA, WHICH IS THE HONEST RESULT RATHER THAN A DISAPPOINTING ONE.
   * The suite seeds from current source, and `lifecycle_notifications_bundle` — rebuilt from the same
   * edited file — already carries the new catalog row. So the witness is true at baseline, exactly
   * the `estate_release_state_lockdown_bundle` situation, and the harness excludes it from the
   * verdict instead of scoring it.
   *
   * The alternative was to hunt for an observable that happens to discriminate, which the note below
   * names for what it is: choosing an observable to make a number come out right. Atomicity for this
   * artifact rests on structure — pure SQL, exactly one begin/commit, one transaction — all asserted
   * above, plus the corrupted-run check that still executes.
   */
  'db/bundles/halt_notification_bundle.sql':
    "select exists (select 1 from public.notification_event_copy('death_process.halted'))",
  /**
   * ★ PHASE 11-MB. This artifact ships exactly one NEW name, so the witness IS the whole payload: if
   * the routine resolves the bundle applied, and if it does not the bundle left nothing behind. Unlike
   * 11-L this discriminates properly — the name does not exist at baseline, so `applies` and `rollback`
   * are both real observations rather than NO_STATE_DELTA.
   */
  'db/bundles/fiduciary_discovery_bundle.sql':
    "select to_regprocedure('public.get_my_fiduciary_estates()') is not null",
  /**
   * ★ PHASE 11-NR. Like 11-L, this artifact CREATES NO NEW NAME — it replaces one file's worth of
   * existing functions — so `to_regprocedure(...) is not null` cannot testify: every name exists
   * before it runs and after. The only observable state delta is BODY CONTENT, and the body content
   * that matters is the one the remediation changes: whether the deployed `challenge_death_process`
   * settles the case from the widened set or only from 'open'.
   *
   * ★ AND IT WILL REPORT NO_STATE_DELTA, WHICH IS THE HONEST ANSWER AND NOT A DISAPPOINTING ONE.
   * The harness seeds its baseline from current source, and `death_verification_bundle` — rebuilt
   * from the same edited file — already carries the corrected body. So the witness is true before
   * this artifact runs, exactly as it is for `halt_notification_bundle` and
   * `estate_release_state_lockdown_bundle`, and the harness excludes it from the verdict rather
   * than scoring it.
   *
   * The alternative was to hunt for some observable that happens to discriminate here, which is
   * choosing an observable to make a number come out right. Atomicity for this artifact rests on
   * structure instead — pure SQL, exactly one begin/commit, one transaction, all asserted above —
   * and the corrupted-run injection still executes against it either way.
   */
  /**
   * ★ PHASE 11-OBR / OB-1. Unlike its neighbours this artifact DOES create a new observable — the
   * `claimed_at` column — so the witness discriminates properly rather than reporting NO_STATE_DELTA:
   * the column does not exist at baseline, so `applies` and `rollback` are both real observations.
   *
   * The column is the right witness rather than the routine body: it is what the migration half
   * adds, it is the thing without which the reclaim predicate cannot even parse, and a half-applied
   * bundle that created the column but not the routine would still be caught by the SQL suite's own
   * control. A function-body probe would instead be true both before and after on any database where
   * `outbox_safety.sql` had ever been pasted.
   */
  'db/bundles/owner_notice_claim_visibility_bundle.sql':
    "select exists (select 1 from information_schema.columns "
    + "where table_schema = 'public' and table_name = 'owner_notice_outbox' "
    + "and column_name = 'claimed_at')",
  'db/bundles/challenge_settlement_bundle.sql':
    "select exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace "
    + "where n.nspname = 'public' and p.proname = 'challenge_death_process' "
    + "and p.prosrc like '%status in (''open'', ''verified'')%')",
  /**
   * ★ PHASE 11-MC. This artifact creates no new NAME — it replaces four existing bodies — so the witness
   * is BODY CONTENT: whether `provision_from_invitation` carries the `kind` gate.
   *
   * ★ IT REPORTS NO_STATE_DELTA, AND THE FIRST VERSION OF THIS COMMENT PREDICTED IT WOULD NOT. The
   * prediction was that the seeded source for the other bundles would still hold the pre-correction body
   * until this artifact applied. It does not: `lifecycle_notifications_bundle` ALSO carries
   * `provision_from_invitation`, and it is rebuilt from the same corrected file, so the corrected body is
   * already installed by the time this bundle runs. The witness is therefore true at baseline.
   *
   * That is the honest outcome rather than a fault — the same shape as `halt_notification_bundle`, and
   * the harness excludes such a witness from the verdict instead of scoring it. Hunting for an observable
   * that happened to discriminate would be choosing a measurement to make a number come out right.
   * Atomicity here rests on structure: pure SQL, exactly one transaction, both asserted above, plus the
   * corrupted-run check that still executes.
   */
  'db/bundles/provisioning_correction_bundle.sql':
    "select prosrc like '%v_is_fiduciary%' from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname='public' and p.proname='provision_from_invitation'",
};

const witnessTrue = (q) => {
  const r = psql(`${q};`, ['-A', '-t']);
  return (r.stdout ?? '').trim() === 't';
};

/* ── 2 · APPLIES · and 3 · ROLLS BACK ────────────────────────────────────────────────────────── */
console.log('2 · APPLIES · 3 · ROLLS BACK ON MID-ARTIFACT FAILURE\n');
let failed = false;
for (const a of ARTIFACTS) {
  const sql = readFileSync(join(ROOT, a), 'utf8');
  const witness = WITNESS[a];
  if (!witness) die(2, `CANNOT VERIFY — no witness object defined for ${a}`);

  /**
   * ★ THE CORRUPTION GOES AT A PROVABLY TOP-LEVEL BOUNDARY, AFTER REAL WORK HAS BEEN DONE.
   *
   * The first version spliced at an arbitrary line offset and the instrument reported failure for
   * every bundle — correctly, and not for the reason it appeared. An arbitrary line can land INSIDE
   * a `$function$ … $function$` body, where the injected statement becomes part of the function's
   * stored text instead of a statement: the file then applies perfectly, no error occurs, and the
   * "rollback" check is measuring nothing. That is the vacuous direction, and it is why the
   * injection point is now the `-- ==== <path> ====` separator the bundler writes BETWEEN parts —
   * a position guaranteed to be at statement level and outside every dollar-quoted body.
   *
   * A separator past the start is chosen so the transaction has genuinely created objects before it
   * dies; injecting at the top would abort before anything existed and prove rollback vacuously.
   */
  const lines = sql.split('\n');
  const boundaries = lines
    .map((l, i) => [l, i])
    .filter(([l]) => /^-- ==== /.test(l))
    .map(([, i]) => i);
  /**
   * ★ A SINGLE-PART BUNDLE HAS NO MID-BUNDLE SEPARATOR, AND THAT IS NOT A REASON TO SKIP IT.
   *
   * Phase 11-I ships one function, so there is no second `-- ==== ` boundary to splice at. The
   * property under test is unchanged — after an error inside the transaction, does the object
   * survive? — so the injection point becomes the last top-level statement boundary AFTER the
   * final dollar-quoted body closes. That is still provably outside every `$function$ … $function$`
   * (the hazard the separator rule exists to avoid), and it still lands after real work: the
   * function has been created by then, so a passing rollback check means the wrapper genuinely
   * discarded a created object rather than aborting before anything existed.
   *
   * Refusing to verify here would have been the comfortable choice and the wrong one: it would
   * leave the only artifact this phase asks the operator to paste as the only artifact whose
   * atomicity was never executed.
   */
  let at;
  if (boundaries.length >= 2) {
    at = boundaries[Math.max(1, Math.floor(boundaries.length / 2))];
  } else {
    const closes = lines
      .map((l, i) => [l, i])
      .filter(([l]) => /^\$function\$;\s*$|^\$\$;\s*$/.test(l))
      .map(([, i]) => i);
    if (closes.length === 0) {
      /**
       * ★ NO DOLLAR-QUOTING AT ALL MEANS EVERY LINE IS TOP-LEVEL — but that must be PROVEN, not
       * assumed from the absence of a terminator. The hazard this whole routine defends against is
       * an injection landing inside `$function$ … $function$`, where it becomes inert text and the
       * rollback check silently measures nothing. If the artifact contains no dollar-quote opener
       * whatsoever, that hazard cannot exist and the line after the single part separator is a
       * sound injection point.
       *
       * The privilege-only hotfix artifact is exactly this shape: one `revoke`, no function bodies.
       * Refusing to verify it would leave a security artifact as the only one never executed.
       */
      if (/\$[A-Za-z_]*\$/.test(sql)) {
        die(2, `CANNOT VERIFY — ${a} has ${boundaries.length} part separator(s), no dollar-quote `
          + 'terminator, yet contains dollar-quoting; no provably top-level injection point exists.');
      }
      if (boundaries.length !== 1) {
        die(2, `CANNOT VERIFY — ${a} has no dollar-quoting but ${boundaries.length} separators; `
          + 'expected exactly one to anchor the injection.');
      }
      at = boundaries[0] + 1;
    } else {
      at = closes[closes.length - 1] + 1;
    }
  }
  const corrupted = [...lines.slice(0, at),
    'select this_function_does_not_exist_aw_probe();',
    ...lines.slice(at)].join('\n');

  /**
   * ★ THE VERDICT IS THE DATABASE STATE, NOT PSQL'S EXIT CODE. Whether a client stops at the first
   * error is a client setting (`ON_ERROR_STOP`), and the Supabase editor's choice is not knowable
   * here — which is the whole reason the artifact carries its own transaction. So the question
   * asked is the one that survives any client: after a mid-file error, does the object exist?
   *
   * Run WITHOUT ON_ERROR_STOP deliberately: that is the WEAKER client behaviour (keep going after
   * an error), so proving rollback under it proves it under the stricter one too.
   */
  const rBad = psql(corrupted);
  const erroredBad = /ERROR/.test(`${rBad.stderr ?? ''}${rBad.stdout ?? ''}`);
  /**
   * ★ A WITNESS THAT IS ALREADY TRUE BEFORE THE ARTIFACT RUNS PROVES NOTHING, AND THIS HARNESS MUST
   * SAY SO RATHER THAN SCORE IT.
   *
   * The lockdown artifact withdraws a privilege that the rebuilt estate bundle ALSO withdraws, so in
   * a database seeded from current source the end state is present before the artifact executes.
   * Its witness is therefore true in every run — corrupted or intact — and both `applies` and
   * `rollback` become meaningless rather than merely inconvenient.
   *
   * Checking the witness BEFORE the corrupted run turns that into an explicit classification. A
   * baseline-true witness is reported as NO_STATE_DELTA and excluded from the pass/fail verdict; it
   * is never counted as a pass. The alternative — picking a witness that happens to discriminate —
   * would be choosing an observable to make a number come out right.
   */
  const baselineTrue = witnessTrue(witness);
  const survivedBad = witnessTrue(witness);
  const rollbackOk = erroredBad && !survivedBad;

  const rGood = psql(sql);
  const appliedOk = rGood.status === 0 && witnessTrue(witness);

  if (baselineTrue) {
    console.log(`  ⊘ ${a.split('/').pop().padEnd(46)} NO_STATE_DELTA — witness already true at baseline`);
    console.log('        This artifact\'s effect is already present in the seeded source, so no');
    console.log('        state change can be observed here. Atomicity rests on structure instead:');
    console.log('        one statement inside one transaction, asserted by the pure-SQL and');
    console.log('        exactly-one-begin/commit checks above. NOT counted as a pass.');
    classified.push(a);
    continue;
  }
  console.log(`  ${appliedOk ? '✓' : '✗'} ${a.split('/').pop().padEnd(46)} applies=${appliedOk}  rollback=${rollbackOk}`);
  if (!appliedOk) {
    console.log(`      apply stderr: ${(rGood.stderr || '').trim().split('\n').slice(-2).join(' | ')}`);
    failed = true;
  }
  if (!rollbackOk) {
    console.log('      ✗ a mid-artifact failure did NOT roll back cleanly');
    console.log(`        error_observed=${erroredBad}  witness_present_after_failure=${survivedBad}`);
    if (!erroredBad) {
      console.log('        (no error was even produced — the injection did not land at statement level,');
      console.log('         so this run proves nothing; fix the instrument before trusting a verdict)');
    }
    failed = true;
  }
}

cleanup();
if (failed) {
  console.error('\n✗ ATOMICITY NOT PROVEN — do not hand these artifacts to an operator.');
  process.exit(1);
}
console.log('\n✓ OPERATOR ARTIFACTS ARE PURE SQL, APPLY CLEANLY, AND ROLL BACK COMPLETELY');
if (classified.length > 0) {
  // ★ THE SUMMARY MAY NOT BE QUOTABLE AS COVERING WHAT IT SKIPPED. A banner that says every
  // artifact rolls back, printed in a run where one was never state-tested, is the kind of
  // sentence that gets pasted into a report and believed.
  console.log(`  EXCEPT ${classified.length} artifact(s) CLASSIFIED NO_STATE_DELTA (not state-tested here):`);
  for (const c of classified) console.log(`    ⊘ ${c}`);
}
console.log('  Each was executed against a real Postgres: once corrupted mid-file (must fail and');
console.log('  leave nothing behind) and once intact (must succeed and create its witness object).');
console.log('  NOT established here: how the Supabase Web SQL Editor itself splits or wraps a paste.');
console.log('  That is why each artifact carries its own begin;/commit; — correctness does not');
console.log('  depend on the editor, so that residual unknown is UNVERIFIABLE rather than assumed.');
