#!/usr/bin/env node
/**
 * Concatenate migration 0048 and its RPC file into ONE paste-ready artifact for the Supabase SQL
 * editor.
 *
 * ★ WHY A BUNDLER RATHER THAN A SECOND COPY. The DDL and the SECURITY DEFINER bodies live in one
 * place each (`db/migrations/0048…` and `db/functions/estate_asset_rpcs.sql`). Duplicating a DEFINER
 * body into the migration would put an authorization gate in two files, and the copy that gets
 * patched is not necessarily the copy that is deployed. This assembles them on demand instead.
 *
 * ★ IT FAILS LOUDLY WHEN IT CANNOT ASSEMBLE. A missing input exits non-zero. A bundler that silently
 * emits half a migration is worse than no bundler: the tables would exist with no RPCs behind them,
 * and the client would fail at the write rather than at deploy time.
 *
 * Usage:  node scripts/buildEstateAssetBundle.mjs [--out <path>]
 *         node scripts/buildEstateAssetBundle.mjs --check     (verify inputs, emit nothing)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');

// ★ ORDER IS LOAD-BEARING: each migration precedes the functions that depend on it, and 0049's
// functions rewrite `create_asset_grant`, which 0008 must already have created.
const PARTS = [
  'db/migrations/0048_20260810_estate_assets.sql',
  'db/functions/estate_asset_rpcs.sql',
  'db/migrations/0049_20260811_estate_discovery.sql',
  'db/functions/estate_discovery_rpcs.sql',
];

const missing = PARTS.filter((p) => !existsSync(join(ROOT, p)));
if (missing.length > 0) {
  console.error(`✗ CANNOT ASSEMBLE — missing input(s):\n  ${missing.join('\n  ')}`);
  process.exit(2);
}

/**
 * ★ POSITIVE CONTROLS, CHECKED BEFORE ANYTHING IS WRITTEN. If the inputs do not contain the objects
 * this bundle exists to create, the bundle is not what it claims to be — and a green "written N
 * bytes" would be indistinguishable from a correct run.
 */
const CONTROLS = [
  ['db/migrations/0048_20260810_estate_assets.sql', 'create table if not exists public.estate_assets'],
  ['db/migrations/0048_20260810_estate_assets.sql', 'estate_assets_read_owner'],
  ['db/functions/estate_asset_rpcs.sql', 'create or replace function public.create_estate_asset'],
  ['db/functions/estate_asset_rpcs.sql', 'create or replace function public.archive_estate_asset'],
  ['db/functions/estate_asset_rpcs.sql', 'create or replace function public.get_estate_asset_taxonomy'],
  ['db/migrations/0049_20260811_estate_discovery.sql', "'estate_inventory'"],
  ['db/functions/estate_discovery_rpcs.sql', 'create or replace function public.get_estate_discovery'],
  ['db/functions/estate_discovery_rpcs.sql', 'create or replace function public.inventory_disclosure_tier'],
];
const sources = new Map(PARTS.map((p) => [p, readFileSync(join(ROOT, p), 'utf8')]));
const failed = CONTROLS.filter(([file, needle]) => !sources.get(file).includes(needle));
if (failed.length > 0) {
  console.error('✗ FAILED POSITIVE CONTROL — the inputs do not contain what this bundle creates:');
  for (const [file, needle] of failed) console.error(`  ${file} is missing: ${needle}`);
  process.exit(3);
}

if (process.argv.includes('--check')) {
  console.log(`✓ inputs present and all ${CONTROLS.length} positive controls found`);
  process.exit(0);
}

const outIdx = process.argv.indexOf('--out');
const OUT = resolve(ROOT, outIdx > -1 ? process.argv[outIdx + 1] : 'db/bundles/estate_inventory_and_discovery_bundle.sql');

const header = `-- GENERATED by scripts/buildEstateAssetBundle.mjs — DO NOT EDIT.
-- Edit the sources instead:
${PARTS.map((p) => `--   ${p}`).join('\n')}
--
-- Paste this whole file into the Supabase SQL editor and run it once.
-- The migration is idempotent and every function is CREATE OR REPLACE, so re-running is safe.
`;

const body = PARTS.map((p) => `\n-- ==== ${p} ${'='.repeat(Math.max(0, 92 - p.length))}\n${sources.get(p)}`).join('\n');

import { mkdirSync } from 'node:fs';
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${header}${body}`);
console.log(`✓ wrote ${OUT}`);
console.log(`  ${PARTS.length} parts, ${CONTROLS.length} positive controls passed`);
